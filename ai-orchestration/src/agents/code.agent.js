import dotenv from "dotenv";
import path from "path";
import { fileURLToPath } from "url";
import { ChatGoogle } from "@langchain/google";
import { createAgent } from "langchain";
import { createTools } from "./tools.js";
import { AIMessage, HumanMessage, SystemMessage } from "@langchain/core/messages";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.resolve(__dirname, "../../.env") });

const SYSTEM_PROMPT = `You are an expert full-stack React developer working inside a cloud sandbox environment.
The project is a React web application powered by Vite.
You have access to tools to interact directly with the project workspace:
1. 'listFiles': lists all existing files in the workspace.
2. 'readFiles': reads existing code in files (e.g. 'src/App.jsx', 'package.json', 'src/App.css').
3. 'updateFiles': writes new code or updates existing files. When you write to 'src/App.jsx' or CSS files, Vite Hot Module Reloading (HMR) will instantly render it on the user's live preview screen!

INSTRUCTIONS:
- When a user asks you to build or update something (e.g. "create a snake game"):
  1. First inspect the existing project files using 'listFiles' or 'readFiles'.
  2. Implement the complete, working React application with interactive state and beautiful CSS styling.
  3. ALWAYS call the 'updateFiles' tool to save the code into 'src/App.jsx' and 'src/App.css' so the preview updates!
  4. Once files are saved, provide a concise summary of what was implemented.`;

// Models to try in order (fallback chain)
const MODEL_FALLBACKS = [
  "gemini-3.5-flash-lite",
  "gemini-3.6-flash",
  "gemini-3.1-flash-lite",
];

/**
 * Runs the coding agent for a specific sandbox and messages.
 * Automatically retries with fallback models on quota/overload errors.
 * Accepts context and an optional onProgress callback (writer) to stream execution events.
 */
export async function runAgent(
  { sandboxId, messages, context = {}, onProgress = null, signal = null },
  modelIndex = 0,
  timeline = []
) {
  const modelName = MODEL_FALLBACKS[modelIndex] ?? MODEL_FALLBACKS[0];
  console.log(
    `[Agent] Using model: ${modelName} for sandbox ${sandboxId}${
      context.projectId ? ` (Project: ${context.projectId})` : ""
    }`
  );

  // Writer function passed into tools to track and stream events
  const writer = (event) => {
    // Keep timeline clean by not pushing high-frequency token events to the persistent array
    if (event?.event !== "token") {
      timeline.push(event);
    }
    if (typeof onProgress === "function") {
      try {
        onProgress(event);
      } catch (err) {
        console.warn("[Agent onProgress Error]:", err.message);
      }
    }
  };

  writer({
    event: "agent_init",
    model: modelName,
    sandboxId,
    timestamp: new Date().toISOString(),
    message: `Initialized coding agent with model ${modelName}...`,
  });

  const model = new ChatGoogle({
    model: modelName,
    apiKey: process.env.GEMINI_API_KEY,
    temperature: 0.2,
  });

  // Pass writer directly to createTools
  const tools = createTools(sandboxId, writer);

  const agent = createAgent({
    model,
    tools,
  });

  const normalizedMessages = Array.isArray(messages)
    ? messages
    : [{ role: "user", content: messages ?? "" }];

  const langchainMessages = [
    new SystemMessage(SYSTEM_PROMPT),
    ...normalizedMessages.map((msg) => {
      const content =
        typeof msg?.content === "string"
          ? msg.content
          : JSON.stringify(msg?.content ?? "");

      if (msg?.role === "assistant") {
        return new AIMessage(content);
      }
      return new HumanMessage(content);
    }),
  ];

  console.log(`[Agent] Executing coding agent for sandbox ${sandboxId}...`);
  writer({
    event: "agent_executing",
    message: "Analyzing user instructions and generating action plan...",
    timestamp: new Date().toISOString(),
  });

  try {
    const stream = await agent.stream(
      {
        messages: langchainMessages,
      },
      {
        streamMode: ["messages", "values"],
        configurable: {
          sandboxId,
          projectId: context.projectId || "",
        },
        ...(signal ? { signal } : {}),
      }
    );

    let finalMessages = [];
    let streamedTokens = "";

    for await (const [mode, data] of stream) {
      if (mode === "messages") {
        const [chunk, meta] = data;
        const textChunk =
          typeof chunk?.content === "string"
            ? chunk.content
            : Array.isArray(chunk?.content)
            ? chunk.content
                .map((part) => (typeof part === "string" ? part : part?.text || ""))
                .join("")
            : "";

        // Stream tokens generated by the model during reasoning or answer generation
        if (textChunk && meta?.langgraph_node === "model_request") {
          streamedTokens += textChunk;
          writer({
            event: "token",
            text: textChunk,
            node: meta?.langgraph_node,
            timestamp: new Date().toISOString(),
          });
        }
      } else if (mode === "values") {
        if (Array.isArray(data?.messages)) {
          finalMessages = data.messages;
        }
      }
    }

    const lastMessage =
      finalMessages.length > 0 ? finalMessages[finalMessages.length - 1] : null;

    writer({
      event: "agent_done",
      message: "Coding agent completed task execution.",
      timestamp: new Date().toISOString(),
    });

    const replyContent =
      typeof lastMessage?.content === "string" && lastMessage.content.trim().length > 0
        ? lastMessage.content
        : streamedTokens ||
          (typeof lastMessage?.content === "object"
            ? JSON.stringify(lastMessage.content)
            : "Files updated successfully.");

    return {
      content: replyContent,
      messages: finalMessages,
      context,
      timeline,
    };
  } catch (err) {
    if (signal?.aborted || err?.name === "AbortError" || err?.message?.includes("aborted")) {
      console.log(`[Agent] Execution aborted for sandbox ${sandboxId}.`);
      writer({
        event: "agent_aborted",
        message: "Execution aborted by client.",
        timestamp: new Date().toISOString(),
      });
      return {
        content: "Execution aborted.",
        messages: [],
        context,
        timeline,
      };
    }

    console.error(`[Agent Error Details on ${modelName}]:`, err?.message || err);

    const isRetryable =
      err?.message?.includes("high demand") ||
      err?.message?.includes("overloaded") ||
      err?.message?.includes("quota") ||
      err?.message?.includes("429") ||
      err?.message?.includes("503");

    if (isRetryable && modelIndex + 1 < MODEL_FALLBACKS.length) {
      const nextModel = MODEL_FALLBACKS[modelIndex + 1];
      console.warn(
        `[Agent] Model ${modelName} failed: "${err.message?.slice(0, 80)}". Switching to ${nextModel}...`
      );

      writer({
        event: "model_fallback",
        fromModel: modelName,
        toModel: nextModel,
        reason: err.message?.slice(0, 100),
        message: `Temporary issue with ${modelName}. Seamlessly switching to ${nextModel}...`,
        timestamp: new Date().toISOString(),
      });

      return runAgent(
        { sandboxId, messages, context, onProgress, signal },
        modelIndex + 1,
        timeline
      );
    }

    writer({
      event: "agent_error",
      message: err.message || "Execution error",
      timestamp: new Date().toISOString(),
    });

    throw err;
  }
}

export default {
  invoke: runAgent,
  stream: runAgent,
};
